let a: number = 10;
let b: number = 5;

// Arithmetic
console.log(a + b); 
console.log(a - b); 
console.log(a * b); 
console.log(a / b); 
console.log(a % b); 

// Assignment
a += 5;
console.log(a); 

// Comparison
console.log(a > b);   
console.log(a < b);   
console.log(a === b); 
console.log(a !== b); 

// Logical
console.log(a > b && b > 0); 
console.log(a > b || b < 0); 
console.log(!(a > b));        

// Increment
a++;
console.log(a); 

// Decrement
b--;
console.log(b); 